"""Structural Verilog (not/and/or/buf primitives) for the minimized SOP of a design."""
import re
from dataclasses import dataclass

from ..core.format import format_sop
from ..core.netlist import sop_netlist
from ..ops.minimize import minimize_sop

KEYWORDS = frozenset("""
always and assign automatic begin buf bufif0 bufif1 case casex casez cell cmos config deassign default defparam
design disable edge else end endcase endconfig endfunction endgenerate endmodule endprimitive endspecify endtable
endtask event for force forever fork function generate genvar highz0 highz1 if ifnone incdir include initial inout
input instance integer join large liblist library localparam macromodule medium module nand negedge nmos nor
noshowcancelled not notif0 notif1 or output parameter pmos posedge primitive pull0 pull1 pulldown pullup
pulsestyle_ondetect pulsestyle_onevent rcmos real realtime reg release repeat rnmos rpmos rtran rtranif0 rtranif1
scalared showcancelled signed small specify specparam strong0 strong1 supply0 supply1 table task time tran tranif0
tranif1 tri tri0 tri1 triand trior trireg unsigned use uwire vectored wait wand weak0 weak1 while wire wor xnor xor
""".split())
_PRIMITIVE = {"NOT": "not", "AND": "and", "OR": "or", "BUF": "buf"}


@dataclass
class Module:
    name: str
    inputs: list[str]   # Verilog port names, first input first
    outputs: list[str]
    text: str


def _legal(base):
    legal = re.sub(r"[^A-Za-z0-9_]", "_", base)
    return legal if re.match(r"[A-Za-z_]", legal) else "_" + legal


class _Names:
    """Legal Verilog identifiers, unique within one module."""

    def __init__(self, reserved=()):
        self.taken = set(KEYWORDS) | set(reserved)
        self.renamed = []

    def get(self, base, original=None):
        legal = _legal(base)
        name, k = legal, 1
        while name in self.taken:
            name, k = f"{legal}_{k}", k + 1
        self.taken.add(name)
        if original is not None and name != original:
            self.renamed.append(f"{original} -> {name}")
        return name


def minimized_netlist(design):
    """Covers and netlist of every output's minimized SOP, checked against the truth tables."""
    covers = {f.name: minimize_sop(f) for f in design.functions}
    net = sop_netlist(covers, design.inputs)
    sim = net.simulate()
    for f in design.functions:
        if (sim[f.name] ^ f.on) & ~f.dc:
            raise ValueError(f"the generated circuit for {f.name} does not match its truth table")
    return covers, net


def verilog_module(design, source=None):
    covers, net = minimized_netlist(design)
    names = _Names()
    sig = {x: names.get(x, x) for x in design.inputs}
    sig.update({f.name: names.get(f.name, f.name) for f in design.functions})
    ports = set(sig.values())
    module = _Names(reserved=ports).get(design.name + ("_sop" if _legal(design.name) in ports else ""))
    nodes = net.topo_order()
    nots = sorted((n for n in nodes if n.op == "NOT" and n.name not in covers),
                  key=lambda n: design.inputs.index(n.fanins[0]))
    ands = [n for n in nodes if n.op == "AND" and n.name not in covers]
    for node in nots:
        sig[node.name] = names.get(f"{sig[node.fanins[0]]}_n")
    for k, node in enumerate(ands):
        sig[node.name] = names.get(f"t{k}")
    inner = nots + ands
    used = {x for n in nodes for x in n.fanins}

    lines = [f"// Generated by logicsyn from {source or design.name} (minimized SOP)"]
    lines += [f"//   {f.name} = {format_sop(covers[f.name], f.inputs)}" for f in design.functions]
    if names.renamed:
        lines.append(f"// Renamed for Verilog: {', '.join(names.renamed)}")
    if any(x not in used for x in design.inputs):
        lines.append("// verilator lint_off UNUSED")
    ins = [sig[x] for x in design.inputs]
    outs = [sig[f.name] for f in design.functions]
    ports = ([f"input {', '.join(ins)}"] if ins else []) + [f"output {', '.join(outs)}"]
    lines.append(f"module {module} ({', '.join(ports)});")
    if inner:
        lines.append(f"  wire {', '.join(sig[n.name] for n in inner)};")
    gates = 0
    for node in inner + [net.nodes[f.name] for f in design.functions]:
        out = sig[node.name]
        if node.op in ("CONST0", "CONST1"):
            lines.append(f"  assign {out} = 1'b{node.op[-1]};")
        else:
            gate, gates = names.get(f"g{gates}"), gates + 1
            lines.append(f"  {_PRIMITIVE[node.op]:<3} {gate} ({out}, {', '.join(sig[x] for x in node.fanins)});")
    lines.append("endmodule")
    return Module(module, ins, outs, "\n".join(lines) + "\n")

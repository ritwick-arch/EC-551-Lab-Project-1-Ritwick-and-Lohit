def odd_names():
    names = ["in.1", "and", "g0", "2x"]
    return Design("and", names, [BooleanFunction("out[0]", names, 0b1010101011111110),
                                 BooleanFunction("t0", names, 0b0110)])


DESIGNS = {
    **{p.name: (lambda p=p: load_file(p)) for p in sorted(EXAMPLES.iterdir())},
    "zero": lambda: parse_expr("F(a,b) = 0"),
    "one": lambda: parse_expr("F(a,b) = 1"),
    "not_a": lambda: parse_expr("F(a,b) = a'"),
    "unused": lambda: parse_expr("F(a,b,c) = ab"),
    "odd_names": odd_names,
}


def test_two_outputs_text():
    assert verilog_module(load_file(EXAMPLES / "two_outputs.pla"), "two_outputs.pla").text == """\
// Generated by logicsyn from two_outputs.pla (minimized SOP)
//   F = bc + ac'
//   G = bc + a'b'c'
module two_outputs (input a, b, c, output F, G);
  wire a_n, b_n, c_n, t0, t1, t2;
  not g0 (a_n, a);
  not g1 (b_n, b);
  not g2 (c_n, c);
  and g3 (t0, b, c);
  and g4 (t1, a, c_n);
  and g5 (t2, a_n, b_n, c_n);
  or  g6 (F, t0, t1);
  or  g7 (G, t0, t2);
endmodule
"""


def test_names_are_made_legal():
    m = verilog_module(odd_names())
    assert m.name == "and_2" and m.inputs == ["in_1", "and_1", "g0", "_2x"] and m.outputs == ["out_0_", "t0"]
    assert "// Renamed for Verilog: in.1 -> in_1, and -> and_1, 2x -> _2x, out[0] -> out_0_" in m.text


def test_constants_and_unused_inputs():
    assert "  assign F = 1'b0;" in verilog_module(DESIGNS["zero"]()).text
    assert "  assign F = 1'b1;" in verilog_module(DESIGNS["one"]()).text
    text = verilog_module(DESIGNS["unused"]()).text
    assert "// verilator lint_off UNUSED" in text and "module F_sop (input a, b, c, output F);" in text


def test_wrong_circuit_is_rejected(monkeypatch):
    monkeypatch.setattr("logicsyn.verilog.emit.minimize_sop", lambda f: [])
    with pytest.raises(ValueError, match="does not match"):
        verilog_module(parse_expr("F(a,b) = ab"))


def _write(design, tmp_path):
    m = verilog_module(design)
    path = tmp_path / f"{m.name}.v"
    path.write_text(m.text)
    return m, path


@pytest.mark.parametrize("key", DESIGNS)
def test_verilator_lint_is_clean(key, tmp_path):
    _, path = _write(DESIGNS[key](), tmp_path)
    run = subprocess.run([tool(*VERILATOR), "--lint-only", "-Wall", str(path)], capture_output=True, text=True,
                         env={**os.environ, "VERILATOR_ROOT": VERILATOR_ROOT})
    assert run.returncode == 0 and not run.stderr.strip(), run.stderr


def _yosys_tables(m, path):
    """Truth table of every output, as Yosys evaluates the written Verilog."""
    tables = " ".join(f"-table {x}" for x in m.inputs)
    run = subprocess.run([tool(*YOSYS), "-p", f"read_verilog {path}; hierarchy -top {m.name}; proc; eval {tables}"],
                         capture_output=True, text=True, check=True)
    lines = run.stdout.splitlines()
    head = next(i for i, line in enumerate(lines) if "|" in line and "\\" in line)
    left, right = (part.replace("\\", "").split() for part in lines[head].split("|"))
    tt = dict.fromkeys(right, 0)
    for line in lines[head + 2:]:
        if "|" not in line:
            break
        ins, outs = (part.split() for part in line.split("|"))
        bits = {x: int(v[-1]) for x, v in zip(left, ins)}
        m_index = sum(bits[x] << (len(m.inputs) - 1 - i) for i, x in enumerate(m.inputs))
        for x, v in zip(right, outs):
            tt[x] |= int(v[-1]) << m_index
    return tt


@pytest.mark.parametrize("key", DESIGNS)
def test_yosys_reads_back_the_same_function(key, tmp_path):
    design = DESIGNS[key]()
    m, path = _write(design, tmp_path)
    tt = _yosys_tables(m, path)
    for f, out in zip(design.functions, m.outputs):
        assert (tt[out] ^ f.on) & ~f.dc == 0, f.name

EXAMPLES = Path(__file__).parent.parent / "examples"
YOSYS = ("YOSYS", "/share/pkg.8/yosys/0.48/install/bin/yosys")
VERILATOR = ("VERILATOR", "/share/pkg.7/verilator/4.108/install/bin/verilator_bin")
